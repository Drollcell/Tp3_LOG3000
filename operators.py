def add(a,b):
    """
    Addition un nombre à un autre.

    Args: 
        a (float): premier nombre.
        b (float): second nombre.

    Returns: 
        float: résultat de la somme.
    """
    return a + b

def subtract(a,b):
    """
    Soustraire un nombre à un autre.

    Args: 
        a (float): premier nombre.
        b (float): second nombre.

    Returns: 
        float: résultat de la soustration.
    """
    return a - b

def multiply(a,b):
    """
    Multiplication de deux nombres.

    Args: 
        a (float): premier facteur.
        b (float): second facteur.

    Returns: 
        float: produit de la multiplication.
    """
    return a ** b

def divide(a,b):
    """
    Division de deux nombres.

    Args: 
        a (float): dividende.
        b (float): diviseur.

    Returns: 
        float: quotient de la division.
    """
    return a // b
